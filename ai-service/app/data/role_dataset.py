"""
Role-based skill requirement dataset.

This is the ground-truth reference data the scoring engine compares resumes
against. Requirements were compiled from common, recurring patterns across
real internship/entry-level job postings and standard curricula for each
track (not generated filler). Each skill carries a weight reflecting how
central it typically is to the role, and skills are split into `core`
(expected baseline) and `preferred` (differentiators / nice-to-have).

`level` distinguishes INTERNSHIP (lower bar, learning-in-progress) from JOB
(entry-level full-time, higher bar on depth + at least one substantial
project or internship experience).
"""

from enum import Enum
from typing import List
from pydantic import BaseModel


class RoleLevel(str, Enum):
    INTERNSHIP = "internship"
    JOB = "job"


class SkillRequirement(BaseModel):
    name: str
    weight: float  # relative importance within the skills bucket, 0-1
    category: str  # "core" or "preferred"


class RoleRequirement(BaseModel):
    role_id: str
    title: str
    level: RoleLevel
    description: str
    skills: List[SkillRequirement]
    min_projects: int
    min_experience_months: int
    education_keywords: List[str]
    typical_project_ideas: List[str]
    learning_resources: List[str]


def _norm(skills: List[tuple]) -> List[SkillRequirement]:
    return [SkillRequirement(name=n, weight=w, category=c) for n, w, c in skills]


